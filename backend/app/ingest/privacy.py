"""개인정보 마스킹 — Markdown 을 만들기 전에 지운다.

원본 공문에는 주민등록번호가 들어 있을 수 있다. 변환 단계에서 지워야
data/markdown/, documents.json, 벡터 색인 어디에도 남지 않는다.
원본 파일(업무목록/)은 건드리지 않는다 — 산출물에서만 지운다.
"""

import re

MASK = "[주민번호-마스킹]"

# 921231-1234567 / 921231 - 1234567 꼴.
# 앞 6자리는 생년월일 꼴(월 01-12, 일 01-31)이어야 하고, 붙임표 뒤 첫 숫자는
# 성별·세기 코드(1-8, 외국인등록번호 5-8 포함)다. 2020년 10월부터 뒷자리가
# 무작위라 검증합(checksum)은 조건으로 쓸 수 없다.
# 앞뒤에 다른 숫자가 붙어 있으면(문서번호·금액 등) 주민번호가 아니다.
_RRN = re.compile(
    r"(?<![0-9])"
    r"[0-9]{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12][0-9]|3[01])"
    r"[ \t]*[-‐–—][ \t]*"
    r"[1-8][0-9]{6}"
    r"(?![0-9])"
)

# 붙임표 없이 13자리가 붙은 꼴. 날짜 검증을 통과하는 다른 13자리 수(계좌번호
# 등)를 잘못 지울 수 있지만, 그것도 개인정보라 지워서 손해 볼 것이 없다.
_RRN_BARE = re.compile(
    r"(?<![0-9])"
    r"[0-9]{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12][0-9]|3[01])"
    r"[1-8][0-9]{6}"
    r"(?![0-9])"
)


def mask_rrns(text: str) -> tuple[str, int]:
    """주민등록번호(외국인등록번호 포함)를 지운 본문과 지운 개수."""
    masked, hyphenated = _RRN.subn(MASK, text)
    masked, bare = _RRN_BARE.subn(MASK, masked)
    return masked, hyphenated + bare
